// The same rules must hold on the VERIFY side too, or a token minted by a
// future careless caller would be honoured. Sign these by hand to prove it.
async function handSign(claims) {
  const payload = b64urlEncode(enc.encode(JSON.stringify(claims)));
  const key = await crypto.subtle.importKey(
    'raw', enc.encode(TEST_SECRET), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  const mac = new Uint8Array(await crypto.subtle.sign('HMAC', key, enc.encode(payload)));
  return `${payload}.${b64urlEncode(mac)}`;
}
