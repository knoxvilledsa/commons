// 9f. The other half of the fix: the confirm click still works, and it is now
// the ONLY thing that writes subscription state. A new address must end up
// opted in exactly once, on exactly the lists the signed token names.
{
  stubFetch();
  const env = envWith(fakeKV());
  const token = await mintToken(TEST_SECRET, {
    purpose: PURPOSE_CONFIRM,
    email: 'newcomer@example.org',
    optIn: ['legislative', 'news-passive'],
    optOut: ['news-aggressive'],
    allowed: ALLOWED,
  });
  const res = await confirmGet({
    request: new Request(`https://knoxvilledsa.org/api/confirm?token=${encodeURIComponent(token)}`,
                         { headers: { accept: 'application/json' } }),
    env,
  });
  const body = await res.json();
  check('a valid confirm click succeeds', res.status === 200 && body.ok === true,
        `${res.status} ${JSON.stringify(body)}`);
  const patch = contactCalls().find((c) => c.method === 'PATCH');
  check('the confirm click is what writes the topics', Boolean(patch));
  if (patch) {
    const written = JSON.parse(patch.body);
    check('it opts in to exactly the two lists the token names',
          written.filter((e) => e.subscription === 'opt_in')
            .map((e) => e.id).sort().join(',') === 'topic_legislative,topic_news_passive',
          patch.body);
    check('and opts out of the unpicked news mode, and nothing else',
          written.filter((e) => e.subscription === 'opt_out')
            .map((e) => e.id).join(',') === 'topic_news_aggressive',
          patch.body);
    check('it never writes the global unsubscribed flag',
          !patch.body.includes('unsubscribed'), patch.body);
  }

  // Single use, which only works because CONTACT_KV is now guaranteed present.
  const claims = JSON.parse(new TextDecoder().decode(b64urlDecode(token.split('.')[0])));
  const nonceKey = `sub:used:${claims.n}`;
  check('the nonce was burned', env.CONTACT_KV.store.has(nonceKey));
  // Age it past the scanner-prefetch grace window, then replay.
  env.CONTACT_KV.store.set(nonceKey, String(Math.floor(Date.now() / 1000) - 4000));
  stubFetch();
  const replay = await confirmGet({
    request: new Request(`https://knoxvilledsa.org/api/confirm?token=${encodeURIComponent(token)}`,
                         { headers: { accept: 'application/json' } }),
    env,
  });
  check('a stale replay of a used confirm link is refused',
        replay.status === 409, String(replay.status));
  check('and it touches the contact store on the way to refusing nobody',
        contactCalls().length === 0);
}

