// --- 9. the endpoints, against the attack the review found ------------------
// THE BUG THIS SECTION EXISTS FOR. /api/subscribe used to write every requested
// topic as opt_out before any confirm click. Submitting the public form with a
// real subscriber's address and their list ticked therefore unsubscribed them
// on the spot, with no token and no proof of inbox access, going straight round
// the signed-token scheme that guards /api/unsubscribe.
//
// These run the real handlers with a fake env, a fake KV and a stubbed fetch.

const realFetch = globalThis.fetch;
let calls = [];

function stubFetch({ turnstile = true, sendOk = true } = {}) {
  calls = [];
  globalThis.fetch = async (url, init = {}) => {
    const href = String(url);
    const body = typeof init.body === 'string' ? init.body : String(init.body || '');
    calls.push({ url: href, method: (init.method || 'GET').toUpperCase(), body });
    if (href.includes('challenges.cloudflare.com')) {
      return new Response(JSON.stringify({ success: turnstile }), {
        status: 200, headers: { 'content-type': 'application/json' } });
    }
    if (href.includes('api.resend.com/emails')) {
      return new Response(JSON.stringify({ id: 'test' }), { status: sendOk ? 200 : 502 });
    }
    // Anything the handler sends at the contacts API succeeds, so a test that
    // asserts "no contact call happened" is asserting the absence of the call,
    // never a failure of it.
    return new Response(JSON.stringify({ data: [] }), { status: 200 });
  };
}

function fakeKV() {
  const store = new Map();
  return {
    store,
    async get(k) { return store.has(k) ? store.get(k) : null; },
    async put(k, v) { store.set(k, String(v)); },
  };
}

function envWith(kv, extra = {}) {
  return {
    TURNSTILE_SECRET: 'test-turnstile-secret',
    RESEND_API_KEY: 'test-sending-key',
    RESEND_CONTACTS_API_KEY: 'test-contacts-key',
    SUBSCRIBE_HMAC_KEY: TEST_SECRET,
    RESEND_TOPIC_LEGISLATIVE: 'topic_legislative',
    RESEND_TOPIC_NEWS_AGGRESSIVE: 'topic_news_aggressive',
    RESEND_TOPIC_NEWS_PASSIVE: 'topic_news_passive',
    SITE_ORIGIN: 'https://knoxvilledsa.org',
    CONTACT_KV: kv,
    ...extra,
  };
}

function subscribeRequest(fields, ip = '203.0.113.7') {
  return new Request('https://knoxvilledsa.org/api/subscribe', {
    method: 'POST',
    headers: {
      accept: 'application/json',
      'content-type': 'application/x-www-form-urlencoded',
      'CF-Connecting-IP': ip,
    },
    body: new URLSearchParams({ 'cf-turnstile-response': 'test-token', ...fields }),
  });
}

const contactCalls = () => calls.filter((c) => c.url.includes('api.resend.com/contacts'));
const sendCalls = () => calls.filter((c) => c.url.includes('api.resend.com/emails'));

// 9a. The attack itself. victim@example.org is, as far as this endpoint knows,
// already subscribed to Legislative Watch. A stranger submits the form with
// their address and that list ticked.
{
  stubFetch();
  const env = envWith(fakeKV());
  const res = await subscribePost({
    request: subscribeRequest({ email: 'victim@example.org', legislative_watch: 'on' }),
    env,
  });
  const body = await res.json();
  check('a stranger submitting somebody else’s address still gets a bland ok',
        res.status === 200 && body.ok === true, `${res.status} ${JSON.stringify(body)}`);
  check('THE FIX: no contact-store call is made before the confirm click',
        contactCalls().length === 0,
        contactCalls().map((c) => `${c.method} ${c.url} ${c.body}`).join(' | '));
  check('THE FIX: nothing anywhere in the request writes opt_out',
        !calls.some((c) => c.body.includes('opt_out')),
        calls.map((c) => c.body).join(' | '));
  check('exactly one email is sent, to the submitted address and nobody else',
        sendCalls().length === 1
        && JSON.parse(sendCalls()[0].body).to.length === 1
        && JSON.parse(sendCalls()[0].body).to[0] === 'victim@example.org');
  check('the full-access contacts key is never spent on this path',
        !calls.some((c) => c.body.includes('test-contacts-key')));
}

