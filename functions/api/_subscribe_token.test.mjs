// --- 8. the address regex, against the Python senders -----------------------
// An address this side accepts but src/legislative_monitor/send_digest.py and
// src/dsa_news/send.py reject is worse than one refused at signup: it confirms,
// gets written as opted in, and is then skipped at every send forever, visible
// only as an anonymous count in a log. So this is a port of their _ADDR_RE:
//
//   ^[^@\s,;<>"]+@[^@\s,;<>"]+\.[A-Za-z]{2,}$
//
for (const good of [
  'neighbor@example.org',
  'a@b.co',
  'first.last+watch@mail.example.co.uk',
  "o'brien@example.org",
  'x_y-z@sub.domain.example',
]) {
  check(`a real address is accepted: ${good}`, isPlausibleEmail(good));
}
for (const bad of [
  'a,b@example.org',        // comma: Python rejects, the old JS regex did not
  'a;b@example.org',        // semicolon, same
  '<neighbor@example.org>', // angle brackets, as a mail client would paste them
  'neighbor@example.org>',
  '"quoted"@example.org',   // a quote, which the old regex also let through
  'neighbor@example.123',   // numeric TLD
  'neighbor@example.o',     // one-letter TLD
  'neighbor@example.org.',  // trailing dot
  'neighbor@example',       // no dot at all
  'neighbor@.org',
  '@example.org',
  'neighbor example@x.org', // space
  'neighbor@exam ple.org',
  '',
]) {
  check(`a malformed address is refused: ${JSON.stringify(bad)}`, !isPlausibleEmail(bad));
}
