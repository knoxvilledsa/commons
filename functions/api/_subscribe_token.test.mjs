// The security test for the subscribe/confirm/unsubscribe token. RUN IT BEFORE
// PUBLISHING, and re-run it after any change to _subscribe_token.js.
//
//   . stack/commons/public/bin/node-env.sh
//   cd stack/commons/public && node functions/api/_subscribe_token.test.mjs
//
// WHY THIS FILE EXISTS
//
// The token is the only thing standing between a stranger and the chapter's
// mailing lists, and it is a primitive this codebase had no precedent for. So
// it gets adversarial tests rather than a comment saying it looked right.
//
// It is also the INTEROP CONTRACT. The two Python senders mint their own
// List-Unsubscribe tokens with hmac/hashlib, and if the two implementations
// ever disagree by one byte, every unsubscribe link in the chapter's mail stops
// working silently. The vectors in section 1 were generated by the Python
// reference implementation printed in the header of _subscribe_token.js and are
// asserted here against the shipped JavaScript, so the two cannot drift without
// this failing.

